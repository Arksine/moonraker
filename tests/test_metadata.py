from __future__ import annotations
import json
import pathlib
import pytest
import subprocess
import sys


READ_SIZE = 1024 * 1024
METADATA_SCRIPT = pathlib.Path(__file__).parents[1].joinpath(
    "moonraker/components/file_manager/metadata.py"
)
ORCA_HEADER = "; generated by OrcaSlicer 2.5.0 on 2026-08-14 at 10:25:47\n"


def _get_object_height(tmp_path: pathlib.Path, gcode: str) -> float | None:
    gcode_path = tmp_path.joinpath("test.gcode")
    gcode_path.write_text(gcode)
    result = subprocess.run(
        [sys.executable, str(METADATA_SCRIPT), "-f", gcode_path.name,
         "-p", str(tmp_path)],
        check=True,
        capture_output=True,
        text=True,
    )
    metadata = json.loads(result.stdout)["metadata"]
    return metadata.get("object_height")


def test_prusa_object_height_prefers_header_max_z_height(
    tmp_path: pathlib.Path
):
    gcode = (
        ORCA_HEADER + "; max_z_height: 96.28\n" + "x" * (READ_SIZE * 2) +
        "; CONFIG_BLOCK_START\n"
        "; machine_start_gcode = G1 Z5 F600\n"
        "; CONFIG_BLOCK_END\n"
    )
    assert _get_object_height(tmp_path, gcode) == pytest.approx(96.28)


def test_prusa_object_height_uses_footer_max_z_height(tmp_path: pathlib.Path):
    gcode = (
        ORCA_HEADER + "x" * (READ_SIZE * 2) +
        "; max_z_height: 96.28\n"
    )
    assert _get_object_height(tmp_path, gcode) == pytest.approx(96.28)


def test_prusa_object_height_uses_orca_layer_change(tmp_path: pathlib.Path):
    gcode = ORCA_HEADER + """\
;LAYER_CHANGE
;Z:0.28
;LAYER_CHANGE
;Z:96.28
; CONFIG_BLOCK_START
; machine_start_gcode = G1 Z100 F600
; CONFIG_BLOCK_END
"""
    assert _get_object_height(tmp_path, gcode) == pytest.approx(96.28)


def test_prusa_object_height_uses_legacy_layer_change(tmp_path: pathlib.Path):
    gcode = ORCA_HEADER + """\
;BEFORE_LAYER_CHANGE
;0.28
;BEFORE_LAYER_CHANGE
;96.28
; prusaslicer_config = begin
; machine_start_gcode = G1 Z100 F600
; prusaslicer_config = end
"""
    assert _get_object_height(tmp_path, gcode) == pytest.approx(96.28)


def test_prusa_object_height_ignores_config_gcode(tmp_path: pathlib.Path):
    gcode = ORCA_HEADER + """\
; CONFIG_BLOCK_START
; machine_start_gcode = G1 Z5 F600
; CONFIG_BLOCK_END
"""
    assert _get_object_height(tmp_path, gcode) is None
